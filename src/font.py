class Font16x16:
    """
    16x16 bitmap font for larger displays.

    This is a scaled version of the 8x8 font.
    """

    def __init__(self):
        """Initialize the font."""
        self._font8 = Font8x8()
        self.width = 16
        self.height = 16

    def get_ch(self, char):
        """
        Get the bitmap data for a character (scaled 2x from 8x8).

        Args:
            char: Single character string

        Returns:
            tuple: (bitmap_data, width, height)
        """
        data8, _, _ = self._font8.get_ch(char)

        # Scale up 2x
        data16 = bytearray(32)  # 16 rows * 2 bytes per row

        for row in range(8):
            byte = data8[row]
            # Expand each bit to 2 bits
            expanded = 0
            for bit in range(8):
                if byte & (1 << (7 - bit)):
                    expanded |= (3 << (14 - bit * 2))

            # Write to two rows
            data16[row * 4] = (expanded >> 8) & 0xFF
            data16[row * 4 + 1] = expanded & 0xFF
            data16[row * 4 + 2] = (expanded >> 8) & 0xFF
            data16[row * 4 + 3] = expanded & 0xFF

        return (bytes(data16), self.width, self.height)
